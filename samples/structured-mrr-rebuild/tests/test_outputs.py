def load_parquet() -> pd.DataFrame:
    assert PARQUET_PATH.exists(), f"Missing required output: {PARQUET_PATH}"
    return pd.read_parquet(PARQUET_PATH)


def load_summary() -> dict:
    assert JSON_PATH.exists(), f"Missing required output: {JSON_PATH}"
    with open(JSON_PATH) as f:
        return json.load(f)


def load_monthly() -> pd.DataFrame:
    assert MONTHLY_PATH.exists(), f"Missing required output: {MONTHLY_PATH}"
    return pd.read_csv(MONTHLY_PATH)


def mrr_lookup(df: pd.DataFrame) -> dict:
    return {
        (row["account_id"], row["month"]): float(row["mrr_usd"])
        for _, row in df.iterrows()
    }


