class TestMRRValues:
    def test_all_account_month_mrr_values(self):
        """Every expected account-month MRR value must match within tolerance."""
        df     = load_parquet()
        lookup = mrr_lookup(df)
        errors = []
        for (acct, month), expected in EXPECTED_MRR.items():
            actual = lookup.get((acct, month))
            if actual is None:
                errors.append(f"  Missing row: ({acct}, {month})")
            elif abs(actual - expected) > TOLERANCE:
                errors.append(
                    f"  ({acct}, {month}): expected {expected:.2f}, got {actual:.2f}"
                )
        assert not errors, "Account-month MRR mismatches:\n" + "\n".join(errors)

    def test_annual_subscription_normalized_to_monthly(self):
        """Annual subscriptions must be divided by 12, not counted as a full-year amount.
        Quarterly subscriptions (÷3) are tested separately in test_quarterly_subscription_normalized_to_monthly."""
        lookup = mrr_lookup(load_parquet())
