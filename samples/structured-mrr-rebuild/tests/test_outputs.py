    def test_catchup_billing_distributes_to_service_months(self):
        """A single catchup invoice with multiple service months must be split by service_start.

        acct_015: one invoice (inv_024, invoice_date 2026-03-01) contains 3 lines:
          line 1 → service_start 2026-01-01 → revenue in Jan
          line 2 → service_start 2026-02-01 → revenue in Feb
          line 3 → service_start 2026-03-01 → revenue in Mar
        This happens when a customer converts from trial to paid and is invoiced retroactively,
        or when a billing system processes arrears in batch.

        Wrong: all revenue in 2026-03 because invoice_date = March → 1275.00 in one row.
        Correct: 425.00 in each of 2026-01, 2026-02, 2026-03.
        Each output row must have source_line_count = 1 (one invoice line per service month).
        """
        df     = load_parquet()
        lookup = mrr_lookup(df)

        for month in ["2026-01", "2026-02", "2026-03"]:
            v = lookup.get(("acct_015", month))
            assert v is not None, (
                f"acct_015 missing from {month} — catchup invoice lines may be grouped by "
                f"invoice_date (March) instead of service_start"
            )
            assert abs(v - 425.00) <= TOLERANCE, (
                f"acct_015 {month}: expected mrr_usd=425.00, got {v}"
            )

        v_mar = lookup.get(("acct_015", "2026-03"))
        assert v_mar is not None and abs(v_mar - 425.00) <= TOLERANCE, (
            f"acct_015 March should be 425.00 (one line), not 1275.00 (all 3 lumped): got {v_mar}"
        )

        # source_line_count must be 1 for each month — confirms the agent split the invoice by
        # service_start rather than grouping all 3 lines into a single March row (count=3).
        acct15 = df[df["account_id"] == "acct_015"].set_index("month")
        for month in ["2026-01", "2026-02", "2026-03"]:
            if month in acct15.index:
                slc = int(acct15.loc[month, "source_line_count"])
                assert slc == 1, (
                    f"acct_015 {month}: source_line_count={slc}, expected 1. "
                    f"A count of 3 in March means all 3 catchup lines were grouped by "
                    f"invoice_date instead of service_start."
                )

